--changeset houssem:V005-create-migration-execution-request-table
CREATE TABLE MIGRATION_EXECUTION_REQUEST (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    REQUEST_TYPE VARCHAR2(30) NOT NULL,
    PRIORITY VARCHAR2(20) DEFAULT 'NORMAL' NOT NULL,
    REASON VARCHAR2(1000),

    STATUS VARCHAR2(30) DEFAULT 'QUEUED' NOT NULL,

    COMMAND VARCHAR2(500),
    EXIT_CODE NUMBER,

    OUTPUT CLOB,
    ERROR CLOB,
    VALIDATION_SUMMARY CLOB,

    REQUESTED_BY VARCHAR2(100) DEFAULT 'SYSTEM' NOT NULL,

    REQUESTED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    STARTED_AT TIMESTAMP,
    FINISHED_AT TIMESTAMP,
    DURATION_MS NUMBER
);

--rollback DROP TABLE MIGRATION_EXECUTION_REQUEST;


--changeset houssem:V006-add-environment-to-execution-request
